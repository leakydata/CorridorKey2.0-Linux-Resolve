#!/usr/bin/env python3
"""Install the CorridorKey menu entries into DaVinci Resolve Studio (Linux) and write the config.

    python3 resolve/install.py                                    # install (checkout = parent of resolve/)
    python3 resolve/install.py --ck-dir /path/to/CorridorKey2.0   # or point at another checkout
    python3 install.py --uninstall                                # remove the menu entries

Stdlib only. Re-runnable. Never touches the CorridorKey checkout.
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT_DIR = os.path.expanduser("~/.local/share/DaVinciResolve/Fusion/Scripts/Utility")
CONFIG = os.path.expanduser("~/.config/corridorkey-resolve/config.json")
CLI_LINK = os.path.expanduser("~/.local/bin/corridorkey-resolve")

STUB = '''# Generated by CorridorKey install.py - edit corridorkey_resolve.py, not this file.
import sys
sys.path.insert(0, {here!r})
import corridorkey_resolve
try:
    _r = resolve
except NameError:
    import DaVinciResolveScript as _d
    _r = _d.scriptapp("Resolve")
corridorkey_resolve.launch(_r, mode={mode!r}, hint={hint!r})
'''
ENTRIES = {  # menu file name: (mode, hint)
    "CorridorKey - Key selected clip.py": ("video", None),                 # ProRes 4444 straight-alpha cutout
    "CorridorKey - Key selected clip (HDR EXR).py": ("exr", None),         # linear half-float EXR sequence
    "CorridorKey - Key person (no green screen).py": ("video", "person"),  # automatic person matte as a hint
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ck-dir", default=os.path.dirname(HERE),
                    help="CorridorKey checkout containing infer.py and a working venv (default: this repo)")
    ap.add_argument("--uninstall", action="store_true")
    ap.add_argument("--no-hint-model", action="store_true",
                    help="don't pre-download the person-matte model (about 233 MB; else fetched on first use)")
    a = ap.parse_args()

    if a.uninstall:
        for n in ENTRIES:
            p = os.path.join(SCRIPT_DIR, n)
            if os.path.exists(p):
                os.remove(p)
                print("removed", p)
        if os.path.islink(CLI_LINK) and os.path.realpath(CLI_LINK) == os.path.join(HERE, "ck.py"):
            os.remove(CLI_LINK)
            print("removed", CLI_LINK)
        return

    ck = os.path.abspath(os.path.expanduser(a.ck_dir))
    py = os.path.join(ck, "venv", "bin", "python")
    for need in (os.path.join(ck, "infer.py"), py, os.path.join(ck, "weights", "corridorkey_v2.safetensors")):
        if not os.path.exists(need):
            sys.exit("missing %s - follow the upstream README setup first (venv + download_weights.py)" % need)
    for exe in ("ffmpeg", "ffprobe"):
        if not any(os.access(os.path.join(d, exe), os.X_OK) for d in os.environ["PATH"].split(os.pathsep)):
            sys.exit("%s not found on PATH" % exe)

    os.makedirs(os.path.dirname(CONFIG), exist_ok=True)
    cfg = {}
    if os.path.exists(CONFIG):
        with open(CONFIG) as f:
            cfg = json.load(f)
    cfg.update(ck_dir=ck, python=py)
    with open(CONFIG, "w") as f:
        json.dump(cfg, f, indent=2)
    print("config:", CONFIG)

    os.makedirs(SCRIPT_DIR, exist_ok=True)
    for name, (mode, hint) in ENTRIES.items():
        p = os.path.join(SCRIPT_DIR, name)
        with open(p, "w") as f:
            f.write(STUB.format(here=HERE, mode=mode, hint=hint))
        print("installed", p)
    cli = os.path.join(HERE, "ck.py")
    try:  # command-line / AI-agent interface: `corridorkey-resolve doctor|list|key|status|jobs`
        os.makedirs(os.path.dirname(CLI_LINK), exist_ok=True)
        if os.path.lexists(CLI_LINK):
            os.remove(CLI_LINK)
        os.symlink(cli, CLI_LINK)
        print("installed", CLI_LINK, "->", cli)
    except OSError as ex:
        print("could not link the CLI (%s); run it as: python3 %s" % (ex, cli))
    if not a.no_hint_model:  # torchvision DeepLabV3 for "Key person (no green screen)"; never bundled
        print("fetching the person-matte model (about 233 MB, once) ...")
        r = subprocess.run([py, os.path.join(HERE, "hint_matte.py"), "--download"])
        if r.returncode:
            print("could not fetch it now; it will be downloaded the first time the person hint is used")
    print("Restart Resolve if it is open, then: Workspace > Scripts > Utility > CorridorKey ...")


if __name__ == "__main__":
    main()
